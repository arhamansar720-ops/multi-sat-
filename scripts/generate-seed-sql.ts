/**
 * Writes supabase/seed.sql from the bundled question bank. `supabase db reset`
 * runs it automatically for local development; for hosted projects you can
 * paste it into the SQL editor or use `npm run db:seed`.
 *   npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { bankVersion, catalogRows } from "../src/lib/server/question-sync";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) return `array[${v.map(lit).join(", ")}]::text[]`;
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

function upsert(table: string, rows: Record<string, unknown>[], key: string): string {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]!);
  const values = rows.map((r) => `  (${cols.map((c) => (c === "correct" ? `${lit(JSON.stringify(r[c]))}::jsonb` : c === "difficulties" && r[c] === null ? "null" : lit(r[c]))).join(", ")})`);
  const updates = cols.filter((c) => c !== key).map((c) => `${c} = excluded.${c}`).join(", ");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values.join(",\n")}\non conflict (${key}) do update set ${updates};\n\n`;
}

const rows = catalogRows();
const sql =
  `-- Generated by scripts/generate-seed-sql.ts. Do not edit by hand.\n-- Question bank version ${bankVersion()}\n\n` +
  upsert("exams", rows.exams, "id") +
  upsert("courses", rows.courses, "id") +
  upsert("questions", rows.questions, "id") +
  upsert("question_keys", rows.keys, "question_id") +
  upsert("achievements", rows.achievements, "id") +
  `insert into public.app_meta (key, value) values ('question_bank_version', ${lit(bankVersion())})\non conflict (key) do update set value = excluded.value, updated_at = now();\n`;

writeFileSync(join(process.cwd(), "supabase/seed.sql"), sql);
console.log(`✓ Wrote supabase/seed.sql (${rows.questions.length} questions).`);
